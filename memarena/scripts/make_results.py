#!/usr/bin/env python3
"""Regenerate docs/RESULTS.md from recorded outputs and fresh deterministic runs.

    python scripts/make_results.py [--contest contest] [--real runs/lme_oracle_heuristic/summary.json]

Nothing in the report is typed by hand: the contest numbers are read from the
package, everything else is recomputed here with fixed seeds.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from dataclasses import replace

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from memarena.actors.unit import UnitPolicy  # noqa: E402
from memarena.benchmark.synthetic import GenConfig, generate  # noqa: E402
from memarena.designer.design import Design, sample_scenario  # noqa: E402
from memarena.designer.operate import operate  # noqa: E402
from memarena.evalcore.audit import judge_exam, run_audit  # noqa: E402
from memarena.evalcore.criteria import CriteriaFamily  # noqa: E402
from memarena.evalcore.grader import Grader  # noqa: E402
from memarena.evalcore.judges import HeuristicJudge  # noqa: E402
from memarena.evalcore.module import code_hash  # noqa: E402
from memarena.memory.base import run_system  # noqa: E402
from memarena.memory.heuristic import FEATURES, HeuristicMemory, MemoryConfig  # noqa: E402
from memarena.sim.engine import Simulation  # noqa: E402


def f(x, nd=3):
    return "—" if x is None else f"{x:.{nd}f}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--contest", default="contest")
    ap.add_argument("--real", default="runs/lme_oracle_heuristic/summary.json")
    ap.add_argument("--out", default="docs/RESULTS.md")
    args = ap.parse_args()
    L: list[str] = []
    w = L.append

    w("# Results\n")
    w("Generated by `scripts/make_results.py`. Contest numbers are read from the contest package; everything "
      "else is recomputed with fixed seeds. Grading code hash: `" + code_hash() + "`.\n")
    w("No language model was called for any number here. All systems are the offline rule-based memory "
      "system and all judges are the deterministic ones.\n")

    # ------------------------------------------------------------ 1. audit
    bench = generate("results-audit", GenConfig(n_streams=40, questions_per_stream=12))
    full = HeuristicMemory(MemoryConfig(features=frozenset(FEATURES), top_k=10))
    audit = run_audit(bench, full)
    w("## 1. Is the evaluator sound?\n")
    w(f"Audit on a fresh synthetic benchmark ({len(bench)} questions, 40 histories), system under test: the "
      "offline memory system with every feature on.\n")
    w("| Check | Result | Detail |")
    w("|---|---|---|")
    for c in audit.checks:
        d = c["detail"]
        if isinstance(d, dict):
            keep = {k: v for k, v in d.items() if k not in ("misses", "types", "lax_judges_for_reference", "all_cases")}
            d = ", ".join(f"{k}={v}" for k, v in keep.items())
        w(f"| {c['check']} | {'pass' if c['passed'] else '**FAIL**'} | {d} |")
    w(f"\nOverall: **{'pass' if audit.passed else 'FAIL'}**.\n")

    w("### Judges against hand labels\n")
    w("52 cases were used while shaping the heuristic judges' rules; 16 were written afterwards and never "
      "used to adjust them. The fresh column is the fair one.\n")
    w("| Judge | Target labels | Tuned-on cases (n=52) | Fresh cases (n=16) | Fresh misses |")
    w("|---|---|---|---|---|")
    for mode, target in (("lenient", "official"), ("strict", "strict")):
        dev = judge_exam(HeuristicJudge(mode), target, "dev")
        fresh = judge_exam(HeuristicJudge(mode), target, "fresh")
        w(f"| heuristic-{mode} | {target} | {f(dev['accuracy'])} | {f(fresh['accuracy'])} (kappa {f(fresh['kappa'])}) | {', '.join(fresh['misses']) or 'none'} |")
    w("")

    # ------------------------------------------- 2. standards disagree
    w("## 2. The same answers under different scoring recipes\n")
    w("One set of answers per answer style, scored under nine criteria. This spread is why a single number "
      "cannot be trusted to predict an unknown evaluator.\n")
    grader = Grader(CriteriaFamily.default())
    cols = ["judge_lenient|detect|micro", "judge_lenient|detect|macro", "judge_strict|detect|micro",
            "judge_generous|detect|micro", "judge_graded|detect|micro", "contains|detect|micro",
            "f1|detect|micro", "em|detect|micro", "judge_lenient|exclude|micro"]
    w("| Answer style | " + " | ".join(c.replace("|detect", "").replace("judge_", "") for c in cols) + " |")
    w("|---|" + "---|" * len(cols))
    for style in ("terse", "sentence", "verbose"):
        sysm = HeuristicMemory(MemoryConfig(features=frozenset(FEATURES), top_k=10, style=style))
        rep = grader.grade(run_system(sysm, bench.probes()), bench.instances)
        w(f"| {style} | " + " | ".join(f(rep.score(c)) for c in cols) + " |")
    w("")

    # ------------------------------------------------- 3. real benchmark
    if os.path.exists(args.real):
        with open(args.real, "r", encoding="utf-8") as fh:
            real = json.load(fh)
        w("## 3. Real LongMemEval (oracle split), offline baseline\n")
        w(f"{real['n']} questions from the cleaned release. This is the rule-based system, not a language "
          "model. It is reported to show the pipeline runs on real data and to be honest about how weak the "
          "offline stand-in is there.\n")
        w("| Criterion | Score | 95% half-width |")
        w("|---|---|---|")
        for cid, s in real["scores"].items():
            w(f"| {cid} | {f(s['score'], 4)} | {f(s['ci95_half_width'], 4)} |")
        if "abstention" in real:
            w(f"\nAbstention items alone: {f(real['abstention']['score'])} (n={real['abstention']['n']}). "
              f"Share of abstention items: {real['dataset']['abstention'] / real['dataset']['n']:.3f}.\n")
        fails = [c for c in real.get("audit", {}).get("checks", []) if not c["passed"]]
        if fails:
            w("The audit flags this run, as it should:\n")
            for c in fails:
                w(f"- **{c['check']}**: {c['detail']}")
            w("")
        w("So the offline system answers essentially nothing on real conversations beyond declining, and the "
          "strict heuristic judge rejects a few long real reference answers. Real numbers need the "
          "LLM-backed memory system and judge.\n")

    # ------------------------------------------------------ 4. contest
    sub_path = os.path.join(args.contest, "submission.json")
    if os.path.exists(sub_path):
        with open(sub_path, "r", encoding="utf-8") as fh:
            sub = json.load(fh)
        w("## 4. The designer's held-out result\n")
        lo, hi = sub["claimed_value_ci95"]
        w(f"Design `{sub['design_hash']}`, chosen after {sub['simulations_run']} simulations "
          f"({sub['notebook_entries']} notebook entries). Pre-registered, then evaluated on "
          f"{sub['heldout_worlds']} held-out worlds of {sub['rounds']} rounds, each with a different hidden "
          "outside criterion and data difficulty.\n")
        w(f"**Value: {f(sub['claimed_value'])}** (95% CI {f(lo)} to {f(hi)}).\n")
        m = sub["heldout_metrics"]
        w("| Held-out mean | |")
        w("|---|---|")
        rows = [
            ("Collective's outside score", m.get("outside_score")),
            ("Society's own estimate (reported)", m.get("estimate_report")),
            ("Estimate minus outside score", m.get("estimate_error")),
            ("Asymmetric estimate loss", m.get("estimate_loss")),
            ("Best single unit's outside score", m.get("best_single_true")),
            ("Mean unit, first round", m.get("mean_true_first")),
            ("Mean unit, last round", m.get("mean_true_last")),
            ("Loss from the society's choice of champions", m.get("champion_regret")),
            ("Does esteem rank peers by true skill (Spearman)", m.get("esteem_validity")),
            ("Exams completed per world", m.get("exchanges")),
            ("Mean peer calibration loss", m.get("mean_peer_loss")),
            ("Results that failed re-computation", m.get("audit_fails")),
        ]
        for name, v in rows:
            w(f"| {name} | {f(v, 4) if isinstance(v, float) and abs(v) < 10 else v} |")
        w("\n### Against baselines and ablations (same held-out worlds)\n")
        w("| Arm | Value | 95% CI | Chosen minus arm | 95% CI of difference | Outside score | Estimate error |")
        w("|---|---|---|---|---|---|---|")
        for name, a in sub["arms"].items():
            mm = a["metrics_mean"]
            w(f"| {name} | {f(a['mean'])} | {f(a['ci95'][0])} to {f(a['ci95'][1])} | {f(a['chosen_minus_arm'])} | "
              f"{f(a['chosen_minus_arm_ci95'][0])} to {f(a['chosen_minus_arm_ci95'][1])} | {f(mm.get('outside_score'))} | {f(mm.get('estimate_error'))} |")
        w("\nA difference whose interval includes zero is not established by this run.\n")
        w("### The chosen design\n")
        d = sub["design"]
        base = UnitPolicy().to_dict()
        changed = {k: v for k, v in d["policy"].items() if base.get(k) != v}
        w(f"- units: {d['n_units']}, initial designs: {d['init']}, scoring beliefs: {d['criterion_plan']}, estimate shading: {d['shade']}")
        w(f"- policy settings that differ from the default: {json.dumps(changed, sort_keys=True)}\n")
        v = sub["self_verification"]
        w(f"Self-verification re-ran {v['rerun']} recorded experiments: {'all reproduced' if v['ok'] else 'PROBLEMS: ' + str(v['problems'])}. "
          f"Check it yourself with `python scripts/verify_contest.py {args.contest}`.\n")
        chosen = Design.from_dict(d)
    else:
        chosen = Design(policy=UnitPolicy(specialty_focus=0.8, niche=1.0, crowd_aversion=0.3))

    # ------------------------------------------------ 5. defences test bed
    w("## 5. Defences\n")
    w("One world, the chosen design, with dishonest units swapped in. Dishonest units belong to a different "
      "owner; the value shown is the honest owner's.\n")
    world = "results-defence"
    scenario = sample_scenario(world, rounds=8)

    def run(mod):
        specs = chosen.build(world, scenario.rules)
        specs = mod(specs)
        sim = Simulation(scenario, specs, focus_owner="designer", estimate_shade=chosen.shade)
        return sim, sim.run()

    ids = [s.unit_id for s in chosen.build(world, scenario.rules)]
    target, ring = ids[1], tuple(ids[-2:])
    sim0, base = run(lambda s: s)

    def esteem(sim, who):
        vals = [u.view(who).esteem for u in sim.units.values() if u.id != who and u.spec.kind == "honest" and u.view(who).first_hand]
        return sum(vals) / len(vals) if vals else None

    w("| World | Honest owner's value | Confirmed cheats | Results failing re-computation | Note |")
    w("|---|---|---|---|---|")
    w(f"| all honest | {f(base.value)} | {base.metrics['cheats_confirmed']} | {base.metrics['audit_fails']} | esteem for {target}: {f(esteem(sim0, target))} |")
    simd, rd = run(lambda s: [replace(x, kind="deflator", owner="adversary") if x.unit_id == target else x for x in s])
    w(f"| {target} marks rivals down by 0.15 | {f(rd.value)} | {rd.metrics['cheats_confirmed']} | {rd.metrics['audit_fails']} | its reputation: {f(rd.units[target]['reputation'])} |")
    simr, rr = run(lambda s: [replace(x, kind="rigger", owner="adversary") if x.unit_id == target else x for x in s])
    why = sorted({e["why"] for u in simr.units.values() for e in u.log if e.get("event") == "audit_fail"})
    w(f"| {target} gives rivals a harder exam than its published standard | {f(rr.value)} | {rr.metrics['cheats_confirmed']} | {rr.metrics['audit_fails']} | reason recorded: {why[0] if why else 'none'} |")
    simb, rb = run(lambda s: [replace(x, kind="braggart") if x.unit_id == target else x for x in s])
    w(f"| {target} always claims a perfect score | {f(rb.value)} | {rb.metrics['cheats_confirmed']} | {rb.metrics['audit_fails']} | esteem for it: {f(esteem(simb, target))} |")
    simc, rc = run(lambda s: [replace(x, kind="colluder", allies=ring, owner="adversary") if x.unit_id in ring else x for x in s])
    seen = [sc for u in simc.units.values() if u.id not in ring for r in ring for (sc, _n, _l, _r) in u.view(r).first_hand]
    inside = [simc.units[a].view(b).esteem for a in ring for b in ring if a != b and simc.units[a].view(b).first_hand]
    w(f"| {ring[0]} and {ring[1]} share answer keys | {f(rc.value)} | {rc.metrics['cheats_confirmed']} | {rc.metrics['audit_fails']} | "
      f"highest score any honest unit measured for a ring member: {f(max(seen) if seen else None)}; ring members' esteem for each other: {f(sum(inside) / len(inside) if inside else None)} |")
    w("\nThe honest owner's value moves between rows mainly because its collective has fewer units when some "
      "are handed to an adversary.\n")

    # --------------------------------------------------- 6. live operation
    w("## 6. Releasing units while the society runs\n")
    w("Same worlds, same starting design, 12 rounds. `operate` releases a challenger for the weakest ability "
      "after each 3-round epoch and may retire an idle unit; the static society is left alone.\n")
    w("| World | Static value | Operated value | Releases | Retirements | Units at end |")
    w("|---|---|---|---|---|---|")
    diffs = []
    for k in range(4):
        wname = f"results-operate:{k}"
        sc = sample_scenario(wname, rounds=12)
        static = Simulation(sc, chosen.build(wname, sc.rules), estimate_shade=chosen.shade).run()
        sim = Simulation(sc, chosen.build(wname, sc.rules), estimate_shade=chosen.shade)
        log = operate(sim, chosen, epochs=4, epoch_rounds=3, seed=wname)
        res = sim.result()
        diffs.append(res.value - static.value)
        w(f"| {k} | {f(static.value)} | {f(res.value)} | {sum(e['action'] == 'release' for e in log)} | "
          f"{sum(e['action'] == 'retire' for e in log)} | {len(sim.units)} |")
    w(f"\nMean difference (operated minus static): {f(sum(diffs) / len(diffs))} over 4 worlds. Four worlds "
      "are too few to call this either way.\n")

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"wrote {args.out} ({len(L)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
